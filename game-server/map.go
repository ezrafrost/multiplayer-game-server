type Map struct {
	Width, Height int
	Tiles         []uint8 // row-major: Tiles[y*Width + x]
}

func newMap() *Map {
	tiles := make([]uint8, MapWidth*MapHeight)
	for y := 0; y < MapHeight; y++ {
		for x := 0; x < MapWidth; x++ {
			tiles[y*MapWidth+x] = mapLayout[y][x]
		}
	}
	return &Map{Width: MapWidth, Height: MapHeight, Tiles: tiles}
}

func (m *Map) tileAt(tx, ty int) uint8 {
	if tx < 0 || ty < 0 || tx >= m.Width || ty >= m.Height {
		return TileWall
	}
	return m.Tiles[ty*m.Width+tx]
}

func (m *Map) solidAt(worldX, worldY float32) bool {
	tx := int(worldX) / TileSize
	ty := int(worldY) / TileSize
	t := m.tileAt(tx, ty)
	return t == TileWall || t == TileStructure
}

// solidAABB checks the four corners of a square bounding box centered at (worldX, worldY).
func (m *Map) solidAABB(worldX, worldY, radius float32) bool {
	return m.solidAt(worldX-radius, worldY-radius) ||
		m.solidAt(worldX+radius, worldY-radius) ||
		m.solidAt(worldX-radius, worldY+radius) ||
		m.solidAt(worldX+radius, worldY+radius)
}

// ToBytes serialises the map as [width][height][tile...] for the MAP_DATA packet payload.
func (m *Map) ToBytes() []byte {
	data := make([]byte, 2+len(m.Tiles))
	data[0] = uint8(m.Width)
	data[1] = uint8(m.Height)
	copy(data[2:], m.Tiles)
	return data
}
